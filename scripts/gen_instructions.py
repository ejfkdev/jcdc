#!/usr/bin/env python3
"""Generate crates/classfile/src/instruction.rs — full JVM opcode table + decoder."""

import os

OUT = os.path.join(os.path.dirname(__file__), "..", "crates", "classfile", "src", "instruction.rs")

# (byte, name, fmt)
# fmt: none | u1 | i1 | u2cp | sipush | branch | branch_w | iinc |
#      invokeinterface | invokedynamic | multianewarray | newarray | tableswitch | lookupswitch
OPS = []
def op(b, name, fmt="none"): OPS.append((b, name, fmt))

op(0x00, "Nop"); op(0x01, "AconstNull")
for i, n in enumerate(["M1","0","1","2","3","4","5"]): op(0x02+i, f"Iconst{n}")
op(0x09, "Lconst0"); op(0x0A, "Lconst1")
op(0x0B, "Fconst0"); op(0x0C, "Fconst1"); op(0x0D, "Fconst2")
op(0x0E, "Dconst0"); op(0x0F, "Dconst1")
op(0x10, "Bipush", "i1"); op(0x11, "Sipush", "sipush")
op(0x12, "Ldc", "u1"); op(0x13, "LdcW", "u2cp"); op(0x14, "Ldc2W", "u2cp")
for i, p in enumerate(["I","L","F","D","A"]): op(0x15+i, f"{p}load", "u1")
for i in range(4): op(0x1A+i, f"Iload{i}")
for i in range(4): op(0x1E+i, f"Lload{i}")
for i in range(4): op(0x22+i, f"Fload{i}")
for i in range(4): op(0x26+i, f"Dload{i}")
for i in range(4): op(0x2A+i, f"Aload{i}")
for i, p in enumerate(["I","L","F","D","A","B","C","S"]): op(0x2E+i, f"{p}aload")
for i, p in enumerate(["I","L","F","D","A"]): op(0x36+i, f"{p}store", "u1")
for i in range(4): op(0x3B+i, f"Istore{i}")
for i in range(4): op(0x3F+i, f"Lstore{i}")
for i in range(4): op(0x43+i, f"Fstore{i}")
for i in range(4): op(0x47+i, f"Dstore{i}")
for i in range(4): op(0x4B+i, f"Astore{i}")
for i, p in enumerate(["I","L","F","D","A","B","C","S"]): op(0x4F+i, f"{p}astore")
op(0x57, "Pop"); op(0x58, "Pop2"); op(0x59, "Dup"); op(0x5A, "DupX1"); op(0x5B, "DupX2")
op(0x5C, "Dup2"); op(0x5D, "Dup2X1"); op(0x5E, "Dup2X2"); op(0x5F, "Swap")
for i, p in enumerate(["I","L","F","D"]): op(0x60+i, f"{p}add")
for i, p in enumerate(["I","L","F","D"]): op(0x64+i, f"{p}sub")
for i, p in enumerate(["I","L","F","D"]): op(0x68+i, f"{p}mul")
for i, p in enumerate(["I","L","F","D"]): op(0x6C+i, f"{p}div")
for i, p in enumerate(["I","L","F","D"]): op(0x70+i, f"{p}rem")
op(0x74, "Ineg"); op(0x75, "Lneg"); op(0x76, "Fneg"); op(0x77, "Dneg")
op(0x78, "Ishl"); op(0x79, "Lshl"); op(0x7A, "Ishr"); op(0x7B, "Lshr")
op(0x7C, "Iushr"); op(0x7D, "Lushr")
op(0x7E, "Iand"); op(0x7F, "Land"); op(0x80, "Ior"); op(0x81, "Lor")
op(0x82, "Ixor"); op(0x83, "Lxor")
op(0x84, "Iinc", "iinc")
op(0x85, "I2l"); op(0x86, "I2f"); op(0x87, "I2d")
op(0x88, "L2i"); op(0x89, "L2f"); op(0x8A, "L2d")
op(0x8B, "F2i"); op(0x8C, "F2l"); op(0x8D, "F2d")
op(0x8E, "D2i"); op(0x8F, "D2l"); op(0x90, "D2f")
op(0x91, "I2b"); op(0x92, "I2c"); op(0x93, "I2s")
op(0x94, "Lcmp")
op(0x95, "Fcmpl"); op(0x96, "Fcmpg"); op(0x97, "Dcmpl"); op(0x98, "Dcmpg")
for i, n in enumerate(["eq","ne","lt","ge","gt","le"]): op(0x99+i, "Ifeq" if i==0 else f"If{n.capitalize()}", "branch")
for i, n in enumerate(["eq","ne","lt","ge","gt","le"]): op(0x9F+i, f"IfIcmp{n.capitalize()}", "branch")
op(0xA5, "IfAcmpeq", "branch"); op(0xA6, "IfAcmpne", "branch")
op(0xA7, "Goto", "branch"); op(0xA8, "Jsr", "branch"); op(0xA9, "Ret", "u1")
op(0xAA, "Tableswitch", "tableswitch"); op(0xAB, "Lookupswitch", "lookupswitch")
op(0xAC, "Ireturn"); op(0xAD, "Lreturn"); op(0xAE, "Freturn"); op(0xAF, "Dreturn")
op(0xB0, "Areturn"); op(0xB1, "Return")
op(0xB2, "Getstatic", "u2cp"); op(0xB3, "Putstatic", "u2cp")
op(0xB4, "Getfield", "u2cp"); op(0xB5, "Putfield", "u2cp")
op(0xB6, "Invokevirtual", "u2cp"); op(0xB7, "Invokespecial", "u2cp"); op(0xB8, "Invokestatic", "u2cp")
op(0xB9, "Invokeinterface", "invokeinterface"); op(0xBA, "Invokedynamic", "invokedynamic")
op(0xBB, "New", "u2cp"); op(0xBC, "Newarray", "newarray"); op(0xBD, "Anewarray", "u2cp")
op(0xBE, "Arraylength")
op(0xBF, "Athrow")
op(0xC0, "Checkcast", "u2cp"); op(0xC1, "Instanceof", "u2cp")
op(0xC2, "Monitorenter"); op(0xC3, "Monitorexit")
op(0xC4, "Wide", "wide")
op(0xC5, "Multianewarray", "multianewarray")
op(0xC6, "IfNull", "branch"); op(0xC7, "IfNonnull", "branch")
op(0xC8, "GotoW", "branch_w"); op(0xC9, "JsrW", "branch_w")

OPS.sort(key=lambda x: x[0])
assert len({b for b,_,_ in OPS}) == len(OPS)

L = []
w = L.append
w("//! JVM bytecode instruction decoding (JVMS Chapter 6).")
w("//!")
w("//! Generated by scripts/gen_instructions.py — do not edit by hand.")
w("")
w("/// A decoded bytecode instruction.")
w("#[derive(Debug, Clone, PartialEq)]")
w("pub struct Instruction {")
w("    /// Offset of this instruction in the code array.")
w("    pub pc: u16,")
w("    /// Size in bytes (including the opcode and, for `Wide`, the prefix).")
w("    pub size: u16,")
w("    pub op: Opcode,")
w("    /// First operand: cp index / local slot / absolute branch target / immediate.")
w("    pub a: i32,")
w("    /// Second operand: iinc amount / invokeinterface count / multianewarray dims.")
w("    pub b: i32,")
w("    /// Switch data for Tableswitch/Lookupswitch.")
w("    pub switch_data: Option<Box<SwitchData>>,")
w("}")
w("")
w("#[derive(Debug, Clone, PartialEq)]")
w("pub enum SwitchData {")
w("    /// `targets[i]` is the absolute branch target for key `low + i`.")
w("    Table { default: u16, low: i32, targets: Vec<u16> },")
w("    /// `(match, absolute target)` pairs sorted by match value.")
w("    Lookup { default: u16, pairs: Vec<(i32, u16)> },")
w("}")
w("")
w("/// All JVM opcodes, including legacy jsr/ret and impdep.")
w("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]")
w("#[repr(u8)]")
w("pub enum Opcode {")
for b, name, fmt in OPS:
    w(f"    {name} = 0x{b:02X},")
w("    /// Invalid opcode encountered in the stream.")
w("    Invalid = 0xFF,")
w("}")
w("")
w("impl Opcode {")
w("    pub fn from_byte(b: u8) -> Opcode {")
w("        match b {")
for b, name, fmt in OPS:
    w(f"            0x{b:02X} => Opcode::{name},")
w("            _ => Opcode::Invalid,")
w("        }")
w("    }")
w("")
w("    /// Length in bytes of the instruction with this opcode (excluding any")
w("    /// `wide` prefix and variable-length switch padding).")
w("    pub fn base_len(self) -> u16 {")
w("        match self {")
# compute lengths
lens = {}
for b, name, fmt in OPS:
    if name == "Wide": lens[name] = 1  # special
    elif fmt in ("none",): lens[name] = 1
    elif fmt in ("u1", "i1", "newarray"): lens[name] = 2
    elif fmt in ("u2cp", "sipush", "branch"): lens[name] = 3
    elif fmt == "iinc": lens[name] = 3
    elif fmt in ("invokeinterface", "invokedynamic"): lens[name] = 5
    elif fmt == "multianewarray": lens[name] = 4
    elif fmt == "branch_w": lens[name] = 5
    elif fmt in ("tableswitch", "lookupswitch"): lens[name] = 1  # variable
    else: lens[name] = 1
for name, l in lens.items():
    pass
# group by length
by_len = {}
for name, l in lens.items():
    by_len.setdefault(l, []).append(name)
for l in sorted(by_len):
    names = by_len[l]
    w(f"            " + " | ".join(f"Opcode::{n}" for n in names) + f" => {l},")
w("            Opcode::Invalid => 1,")
w("        }")
w("    }")
w("")
w("    /// True for conditional or unconditional jumps.")
w("    pub fn is_jump(self) -> bool {")
w("        matches!(")
w("            self,")
jumps = [n for b, n, f in OPS if f in ("branch", "branch_w")] + ["Tableswitch", "Lookupswitch"]
lines = []
cur = "            "
for n in jumps:
    piece = f"Opcode::{n}"
    if len(cur) + len(piece) + 3 > 100:
        lines.append(cur.rstrip()); cur = "            "
    cur += piece + " | "
cur = cur.rstrip(" |")
lines.append(cur)
w("\n".join(lines))
w("        )")
w("    }")
w("")
w("    /// True if execution never falls through to pc+size (goto/return/throw/ret/tableswitch...).")
w("    pub fn is_terminal(self) -> bool {")
w("        matches!(")
w("            self,")
terms = ["Goto", "GotoW", "Jsr", "JsrW", "Ret", "Tableswitch", "Lookupswitch",
         "Ireturn", "Lreturn", "Freturn", "Dreturn", "Areturn", "Return", "Athrow"]
cur = "            "
lines = []
for n in terms:
    piece = f"Opcode::{n}"
    if len(cur) + len(piece) + 3 > 100:
        lines.append(cur.rstrip()); cur = "            "
    cur += piece + " | "
cur = cur.rstrip(" |")
lines.append(cur)
w("\n".join(lines))
w("        )")
w("    }")
w("}")
w("")
w("impl Instruction {")
w("    /// For jump instructions, the list of possible successor pcs.")
w("    pub fn targets(&self) -> Vec<u16> {")
w("        match self.op {")
w("            Opcode::Goto | Opcode::GotoW | Opcode::Jsr | Opcode::JsrW => vec![self.a as u16],")
w("            Opcode::Tableswitch => {")
w("                let mut v = Vec::new();")
w("                if let Some(SwitchData::Table { default, targets, .. }) = self.switch_data.as_deref() {")
w("                    v.push(*default);")
w("                    v.extend(targets.iter().copied());")
w("                }")
w("                v")
w("            }")
w("            Opcode::Lookupswitch => {")
w("                let mut v = Vec::new();")
w("                if let Some(SwitchData::Lookup { default, pairs }) = self.switch_data.as_deref() {")
w("                    v.push(*default);")
w("                    v.extend(pairs.iter().map(|(_, t)| *t));")
w("                }")
w("                v")
w("            }")
w("            o if o.is_jump() => vec![self.a as u16, (self.pc as u32 + self.size as u32) as u16],")
w("            _ => vec![],")
w("        }")
w("    }")
w("}")
w("")
w("/// Decode an entire code array. Stops on the first undecodable byte,")
w("/// returning what was decoded so far plus an Invalid instruction marker.")
w("pub fn decode_all(code: &[u8]) -> Vec<Instruction> {")
w("    let mut out = Vec::new();")
w("    let mut pc = 0usize;")
w("    while pc < code.len() {")
w("        match decode_at(code, pc as u16) {")
w("            Some(ins) => {")
w("                pc += ins.size as usize;")
w("                out.push(ins);")
w("            }")
w("            None => {")
w("                out.push(Instruction {")
w("                    pc: pc as u16,")
w("                    size: 1,")
w("                    op: Opcode::Invalid,")
w("                    a: code[pc] as i32,")
w("                    b: 0,")
w("                    switch_data: None,")
w("                });")
w("                break;")
w("            }")
w("        }")
w("    }")
w("    out")
w("}")
w("")
w("/// Decode one instruction at `pc`. Returns None if truncated or invalid.")
w("pub fn decode_at(code: &[u8], pc: u16) -> Option<Instruction> {")
w("    let p = pc as usize;")
w("    let byte = *code.get(p)?;")
w("    let op = Opcode::from_byte(byte);")
w("    let get = |i: usize| -> Option<u8> { code.get(p + i).copied() }")
w("    ;")
w("    let u2 = |i: usize| -> Option<u16> {")
w("        Some(((get(i)? as u16) << 8) | get(i + 1)? as u16)")
w("    };")
w("    let i2 = |i: usize| -> Option<i16> { Some(u2(i)? as i16) };")
w("    let i4 = |i: usize| -> Option<i32> {")
w("        Some(((get(i)? as u32) << 24 | (get(i + 1)? as u32) << 16")
w("            | (get(i + 2)? as u32) << 8 | get(i + 3)? as u32) as i32)")
w("    };")
w("    let target = |off: i32| -> i32 { pc as i32 + off };")
w("    let mut ins = Instruction { pc, size: op.base_len(), op, a: 0, b: 0, switch_data: None };")
w("    match op {")
for b, name, fmt in OPS:
    if fmt == "none": continue
    if fmt == "u1":
        w(f"        Opcode::{name} => ins.a = get(1)? as i32,")
    elif fmt == "i1":
        w(f"        Opcode::{name} => ins.a = get(1)? as i8 as i32,")
    elif fmt == "u2cp":
        w(f"        Opcode::{name} => ins.a = u2(1)? as i32,")
    elif fmt == "sipush":
        w(f"        Opcode::{name} => ins.a = i2(1)? as i32,")
    elif fmt == "branch":
        w(f"        Opcode::{name} => ins.a = target(i2(1)? as i32),")
    elif fmt == "branch_w":
        w(f"        Opcode::{name} => ins.a = target(i4(1)?),")
    elif fmt == "iinc":
        w(f"        Opcode::{name} => {{ ins.a = get(1)? as i32; ins.b = get(2)? as i8 as i32; }}")
    elif fmt == "invokeinterface":
        w(f"        Opcode::{name} => {{ ins.a = u2(1)? as i32; ins.b = get(3)? as i32; }}")
    elif fmt == "invokedynamic":
        w(f"        Opcode::{name} => ins.a = u2(1)? as i32,")
    elif fmt == "multianewarray":
        w(f"        Opcode::{name} => {{ ins.a = u2(1)? as i32; ins.b = get(3)? as i32; }}")
    elif fmt == "newarray":
        w(f"        Opcode::{name} => ins.a = get(1)? as i32,")
    elif fmt == "wide":
        continue
w("        Opcode::Wide => {")
w("            let wop = Opcode::from_byte(get(1)?);")
w("            let index = u2(2)?;")
w("            let (size, b) = match wop {")
w("                Opcode::Iinc => (6u16, i2(4)? as i32),")
w("                Opcode::Iload | Opcode::Lload | Opcode::Fload | Opcode::Dload | Opcode::Aload")
w("                | Opcode::Istore | Opcode::Lstore | Opcode::Fstore | Opcode::Dstore")
w("                | Opcode::Astore | Opcode::Ret => (4, 0),")
w("                _ => return None,")
w("            };")
w("            ins = Instruction { pc, size, op: wop, a: index as i32, b, switch_data: None };")
w("            ins.size = size;")
w("            return Some(ins);")
w("        }")
w("        Opcode::Tableswitch => {")
w("            let pad = (4 - ((p + 1) % 4)) % 4;")
w("            let base = p + 1 + pad;")
w("            let default = i4at(code, base)?;")
w("            let low = i4at(code, base + 4)?;")
w("            let high = i4at(code, base + 8)?;")
w("            if high < low || (high - low) as usize > 65535 { return None; }")
w("            let n = (high - low + 1) as usize;")
w("            let mut targets = Vec::with_capacity(n);")
w("            for i in 0..n {")
w("                let off = i4at(code, base + 12 + 4 * i)?;")
w("                targets.push(target(off) as u16);")
w("            }")
w("            ins.size = (base + 12 + 4 * n - p) as u16;")
w("            ins.a = target(default);")
w("            ins.switch_data = Some(Box::new(SwitchData::Table {")
w("                default: target(default) as u16,")
w("                low,")
w("                targets,")
w("            }));")
w("        }")
w("        Opcode::Lookupswitch => {")
w("            let pad = (4 - ((p + 1) % 4)) % 4;")
w("            let base = p + 1 + pad;")
w("            let default = i4at(code, base)?;")
w("            let npairs = i4at(code, base + 4)?;")
w("            if npairs < 0 || npairs as usize > 65535 { return None; }")
w("            let mut pairs = Vec::with_capacity(npairs as usize);")
w("            for i in 0..npairs as usize {")
w("                let m = i4at(code, base + 8 + 8 * i)?;")
w("                let off = i4at(code, base + 12 + 8 * i)?;")
w("                pairs.push((m, target(off) as u16));")
w("            }")
w("            ins.size = (base + 8 + 8 * npairs as usize - p) as u16;")
w("            ins.a = target(default);")
w("            ins.switch_data = Some(Box::new(SwitchData::Lookup {")
w("                default: target(default) as u16,")
w("                pairs,")
w("            }));")
w("        }")
w("        Opcode::Invalid => return None,")
w("        _ => {}")
w("    }")
w("    Some(ins)")
w("}")
w("")
w("fn i4at(code: &[u8], i: usize) -> Option<i32> {")
w("    let b = code.get(i..i + 4)?;")
w("    Some(i32::from_be_bytes([b[0], b[1], b[2], b[3]]))")
w("}")
w("")
w("#[cfg(test)]")
w("mod tests {")
w("    use super::*;")
w("")
w("    #[test]")
w("    fn decode_simple() {")
w("        // getstatic #2; invokevirtual #3; return")
w("        let code = [0xB2, 0x00, 0x02, 0xB6, 0x00, 0x03, 0xB1];")
w("        let ins = decode_all(&code);")
w("        assert_eq!(ins.len(), 3);")
w("        assert_eq!(ins[0].op, Opcode::Getstatic);")
w("        assert_eq!(ins[0].a, 2);")
w("        assert_eq!(ins[1].op, Opcode::Invokevirtual);")
w("        assert_eq!(ins[2].op, Opcode::Return);")
w("    }")
w("")
w("    #[test]")
w("    fn decode_tableswitch_padding() {")
w("        // at pc=1 so padding applies")
w("        let mut code = vec![0x2Au8 /*aload_0*/, 0xAA, 0, 0 /*pad*/];")
w("        code.extend_from_slice(&10i32.to_be_bytes()); // default offset")
w("        code.extend_from_slice(&0i32.to_be_bytes()); // low")
w("        code.extend_from_slice(&1i32.to_be_bytes()); // high")
w("        code.extend_from_slice(&3i32.to_be_bytes());")
w("        code.extend_from_slice(&5i32.to_be_bytes());")
w("        let ins = decode_all(&code);")
w("        assert_eq!(ins.len(), 2);")
w("        let sw = ins[1].switch_data.as_ref().unwrap();")
w("        match &**sw {")
w("            SwitchData::Table { default, low, targets } => {")
w("                assert_eq!(*default, 11);")
w("                assert_eq!(*low, 0);")
w("                assert_eq!(targets, &vec![4u16, 6]);")
w("            }")
w("            _ => panic!(\"expected table\"),")
