w("        assert_eq!(ins[1].size as usize, code.len() - 1);")
w("    }")
w("")
w("    #[test]")
w("    fn decode_wide_iinc() {")
w("        let code = [0xC4, 0x84, 0x01, 0x00, 0x00, 0x65];")
w("        let ins = decode_all(&code);")
w("        assert_eq!(ins.len(), 1);")
w("        assert_eq!(ins[0].op, Opcode::Iinc);")
w("        assert_eq!(ins[0].a, 256);")
w("        assert_eq!(ins[0].b, 101);")
w("        assert_eq!(ins[0].size, 6);")
w("    }")
w("")
w("    #[test]")
w("    fn decode_branches() {")
w("        // ifeq +5 at pc 0 -> target 5; goto_w -10")
w("        let mut code = vec![0x99, 0x00, 0x05];")
w("        code.push(0xC8);")
w("        code.extend_from_slice(&(-10i32).to_be_bytes());")
w("        let ins = decode_all(&code);")
w("        assert_eq!(ins[0].op, Opcode::Ifeq);")
w("        assert_eq!(ins[0].a, 5);")
w("        assert_eq!(ins[1].op, Opcode::GotoW);")
w("        assert_eq!(ins[1].a, -7);")
w("    }")
w("}")

os.makedirs(os.path.dirname(os.path.abspath(OUT)), exist_ok=True)
with open(os.path.abspath(OUT), "w") as f:
    f.write("\n".join(L) + "\n")
print("generated", os.path.abspath(OUT), len(L), "lines")
